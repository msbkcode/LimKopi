def logout_cases(prefix, username):
    return [
        Case(f"{prefix}_001", "Successful logout", f"'{username}' logged in", "1. Click Logout",
             "Session ended (sessionEnded=true); login page displayed", username,
             lambda c, t: c.post("/api/logout"), 200, lambda b, t: b["sessionEnded"] is True),
        Case(f"{prefix}_002", "Session already ended (A1)", "Session expired / removed", "1. Click Logout",
             "200; sessionEnded=false; login page still displayed", username,
             lambda c, t: (t.db("DELETE FROM sessions"), c.post("/api/logout"))[1], 200, lambda b, t: b["sessionEnded"] is False),
        Case(f"{prefix}_003", "Old session cannot be reused", f"'{username}' logged out",
             "1. Log out\n2. Replay the old session cookie", "401 'Please sign in.'", username,
             lambda c, t: (lambda old: (c.post("/api/logout"), setattr(c, "cookie", old), c.get("/api/bootstrap"))[2])(c.cookie), 401),
    ]


