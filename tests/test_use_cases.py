class UseCaseAcceptanceTest(ServerTestCase):
    pass


def _make(case: Case):
    def test(self):
        c = self.client(case.actor) if case.actor else self.client()
        result = case.run(c, self)
        if case.status is None:
            body = result
        else:
            status, body = result
            expected = case.status if isinstance(case.status, tuple) else (case.status,)
            self.assertIn(status, expected, f"{case.id}: got HTTP {status}: {body}")
        self.assertTrue(case.check(body, self), f"{case.id}: expected result not met: {body}")
    test.__doc__ = f"{case.id} — {case.scenario}"
    return test


for _case in CASES:
    setattr(UseCaseAcceptanceTest, f"test_{_case.id}", _make(_case))


